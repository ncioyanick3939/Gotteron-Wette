let LANG = 'ch';
export function setLang(l) { LANG = l === 'de' ? 'de' : 'ch'; }
export const lang = () => LANG;

// Ein Text übersetze
export function T(s) {
  if (LANG !== 'de' || s == null) return s;
  const str = String(s);
  if (Object.prototype.hasOwnProperty.call(DICT, str)) return DICT[str];
  for (const [re, to] of PATTERNS) if (re.test(str)) return str.replace(re, to);
  return str;
}

const ATTRS = ['placeholder', 'aria-label', 'title', 'alt'];

// S'ganze Stück Siite übersetze (Text-Chnöpf und Attribut)
export function translateDom(root) {
  if (LANG !== 'de' || !root) return;
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const jobs = [];
  for (let n = w.nextNode(); n; n = w.nextNode()) {
    const p = n.parentNode;
    if (p && (p.nodeName === 'SCRIPT' || p.nodeName === 'STYLE')) continue;
    const raw = n.nodeValue;
    const t = raw.trim();
    if (!t || !/[A-Za-zÄÖÜäöü]/.test(t)) continue;
    const out = T(t);
    if (out !== t) jobs.push([n, raw.replace(t, out)]);
  }
  jobs.forEach(([n, v]) => { n.nodeValue = v; });

  const els = root.querySelectorAll('[' + ATTRS.join('],[') + ']');
  els.forEach(el => ATTRS.forEach(a => {
    const v = el.getAttribute(a);
    if (!v) return;
    const out = T(v.trim());
    if (out !== v.trim()) el.setAttribute(a, out);
  }));
}
